//! Receiver-bound scratch-header transfer contracts.
use core::ops::Range;

/// A recognized header-only AES receiver and its boot-preserving write spans.
/// This describes wire representation, not a promise that a target is accepted.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MixedContract {
    programmed: [Range<usize>; 2],
}
impl MixedContract {
    /// The only encrypted range in the uploaded staging image.
    pub fn header_range(&self) -> Range<usize> {
        0x3000..0x3010
    }
    /// Bytes programmed by this receiver when PREPARE preserves boot.
    pub fn programmed_ranges(&self) -> &[Range<usize>] {
        &self.programmed
    }
    /// Plaintext descriptor byte the receiver requires to equal 0xDE.
    pub fn descriptor_byte(&self) -> usize {
        0x1ec056
    }
}

// These are bounded instruction signatures for the two observed compiler
// forms, not image hashes or model/version identifiers. The complete handler
// includes its switch tables, branches, flag stores and literal operands. A
// different instruction or operand is deliberately not treated as equivalent.
// In particular, a scratch AES call alone cannot select mixed transfer.
use super::{analysis::ApplicationAnalysis, decoding::branch_link, entry::application};

struct Form {
    application: &'static [u16],
    header_call: u32,
    selection: u32,
    program_call: u32,
    boot_check_call: u32,
    wrapper: &'static [u16],
    integrity: &'static [u16],
    program: &'static [u16],
    skip_start: u32,
    skip_length: u32,
    skip_final: u32,
}

/// A matched handler whose out-of-line programming code must still be read.
pub(super) struct Candidate {
    form: &'static Form,
    pub(super) wrapper_address: u32,
    pub(super) integrity_address: u32,
}

fn words_match(bytes: &[u8], base: u32, start: u32, expected: &[u16]) -> bool {
    let Some(offset) = start.checked_sub(base).map(|x| x as usize) else {
        return false;
    };
    let Some(end) = offset.checked_add(expected.len() * 2) else {
        return false;
    };
    bytes.get(offset..end).is_some_and(|actual| {
        actual
            .chunks_exact(2)
            .zip(expected)
            .all(|(a, e)| u16::from_le_bytes([a[0], a[1]]) == *e)
    })
}

impl Candidate {
    pub(super) fn inspect(bytes: &[u8], base: u32, analysis: &ApplicationAnalysis) -> Option<Self> {
        if analysis.conflicting_arguments()
            || !analysis.bulk_decoders().is_empty()
            || analysis.scratch_decoders().len() != 1
        {
            return None;
        }
        let handler = application::inspect(bytes, base)?;
        let prologue = application::inspect_prologue(bytes, base, &handler)?;
        application::inspect_flags(bytes, base, &handler, &prologue)?;
        application::inspect_mode_six(bytes, base, &handler, &prologue)?;
        // Both compiler forms place the tag/marker helpers directly before
        // WRITE BUFFER. Their entire code and operands belong to the signature.
        let start = prologue.start.checked_sub(0xdc)?;
        let mut matches = FORMS
            .iter()
            .filter(|form| words_match(bytes, base, start, form.application));
        let form = matches.next()?;
        if matches.next().is_some() {
            return None;
        }
        let header = &analysis.scratch_decoders()[0];
        if header.address != start.checked_add(form.header_call)? {
            return None;
        }
        let range = analysis
            .ranges()
            .iter()
            .find(|r| r.selection.address == start + form.selection)?;
        let signature = range.signature?;
        if signature.offset != 0x10600 || signature.length != 8 {
            return None;
        }
        let wrapper_address = branch_link(bytes, base, start.checked_add(form.program_call)?)?;
        let integrity_address = branch_link(bytes, base, start.checked_add(form.boot_check_call)?)?;
        Some(Self {
            form,
            wrapper_address,
            integrity_address,
        })
    }

    pub(super) fn wrapper_bytes(&self) -> usize {
        self.form.wrapper.len() * 2
    }
    pub(super) fn integrity_bytes(&self) -> usize {
        self.form.integrity.len() * 2
    }
    pub(super) fn program_bytes(&self) -> usize {
        self.form.program.len() * 2
    }

    /// The matched wrapper preserves incoming r0/r1/r2 across setup, stores
    /// destination/source/remaining into the loop's cells and calls its mode-3
    /// loop. Read the actual call target; the two forms use different locations.
    pub(super) fn program_address(&self, wrapper: &[u8]) -> Option<u32> {
        if !words_match(
            wrapper,
            self.wrapper_address,
            self.wrapper_address,
            self.form.wrapper,
        ) {
            return None;
        }
        branch_link(
            wrapper,
            self.wrapper_address,
            self.wrapper_address.checked_add(0x13e)?,
        )
    }

    pub(super) fn bind(
        &self,
        wrapper: &[u8],
        integrity: &[u8],
        program: &[u8],
    ) -> Option<MixedContract> {
        self.program_address(wrapper)?;
        if !words_match(integrity, 0, 0, self.form.integrity)
            || !words_match(program, 0, 0, self.form.program)
        {
            return None;
        }
        // Decode the loop's MOV/LSL operands after matching the complete loop,
        // including its pointer setup, both erase sizes, increments and exits.
        // The signature includes the byte-copy/program helper and its literal
        // operands, binding raw staging bytes to the hardware program buffer.
        // One form preserves 0x1d0000..0x1ec000, the other
        // 0x1c8000..0x1ec000: this must never be a single model-based constant.
        let first = shifted_immediate(program, self.form.skip_start)? as usize;
        let length = shifted_immediate(program, self.form.skip_length)? as usize;
        let final_start = shifted_immediate(program, self.form.skip_final)? as usize;
        let second = first.checked_add(length)?;
        if !(0x10000 < first && first < second && second < final_start && final_start < 0x200000) {
            return None;
        }
        Some(MixedContract {
            programmed: [0x10000..first, second..final_start],
        })
    }
}

fn shifted_immediate(bytes: &[u8], offset: u32) -> Option<u32> {
    let pair = bytes.get(offset as usize..offset as usize + 4)?;
    let mov = u16::from_le_bytes([pair[0], pair[1]]);
    let shift = u16::from_le_bytes([pair[2], pair[3]]);
    let reg = (mov >> 8) & 7;
    if mov & 0xf800 != 0x2000 || shift & 0xf800 != 0 || shift & 7 != reg || (shift >> 3) & 7 != reg
    {
        return None;
    }
    u32::from(mov & 255).checked_shl(u32::from((shift >> 6) & 31))
}

