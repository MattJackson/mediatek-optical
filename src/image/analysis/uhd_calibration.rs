fn literal(image: &[u8], at: usize) -> Result<u32, Error> {
    let op = u16::from_le_bytes(
        image
            .get(at..at + 2)
            .ok_or(Error::Truncated)?
            .try_into()
            .unwrap(),
    );
    let pool = ((at + 4) & !3) + usize::from(op & 255) * 4;
    Ok(u32::from_le_bytes(
        image
            .get(pool..pool + 4)
            .ok_or(Error::Truncated)?
            .try_into()
            .unwrap(),
    ))
}
impl ClassicCalibration {
    /// Bind all six speed thresholds, their doubled index, the startup lookup
    /// and its coefficient/rate identity with the independently matched getter.
    /// Other code layouts refuse; no numeric calibration is transplanted.
    pub fn detect(image: &[u8], state: u32) -> Result<Self, Error> {
        let parameter = ClassicParameter::detect(image, state)?;
        let length = PATTERN.len() * 2;
        if image.len() < length {
            return Err(Error::Truncated);
        }
        let mut result = None;
        for entry in (0..=image.len() - length).step_by(2) {
            if !matches(image, entry, PATTERN) {
                continue;
            }
            let site = entry + 0x196;
            let original_base = literal(image, site)?;
            if literal(image, entry + 0x46)? as usize != parameter.rates
                || (original_base as usize).checked_add(0x58) != Some(parameter.oem_coefficients)
            {
                return Err(Error::InvalidContract);
            }
            let c7_coefficients = match parameter.variant {
                ClassicParameterVariant::MediaSelected => Some(
                    u32::try_from(parameter.coefficients).map_err(|_| Error::InvalidContract)?,
                ),
                ClassicParameterVariant::StateIndependent => None,
            };
            let bound = Self {
                caller: SavedLink::bind(image, entry, site)?,
                site,
                original_base,
                c7_coefficients,
            };
            if result.replace(bound).is_some() {
                return Err(Error::Ambiguous);
            }
        }
        result.ok_or(Error::UnknownLayout)
    }
}
